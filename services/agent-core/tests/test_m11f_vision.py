"""M11 completion: photo reading through the `vision` slot (MDL-23, MDL-06, SEC-05, MDL-25, INP-20, TABLE INP-21a).

Through the engine with scripted local and cloud providers: every photo is made safe before any model sees it; the
main local model reads it when its projector gives it vision; a cloud reader gets a photo only while the cloud tier
is on, after this photo's pre-send notice is accepted, and only the image the local privacy pass gave; declining reads
it locally. Every photo here is generated by the test."""

from __future__ import annotations

import asyncio
import base64
import io
from dataclasses import replace
from pathlib import Path
from typing import Any

from agent_core.contracts import errors as contract_errors
from agent_core.engine.vision import READ_INSTRUCTION, PhotoReading
from agent_core.providers.scripted import ScriptedProvider, default_capabilities
from agent_core.store.images import SafePhoto
from engine_harness import close, make_engine, reply
from PIL import Image
from test_m11d_images import GPS_IFD, _photo_with_gps

LOOP = asyncio.new_event_loop()
READ = "A ball is thrown up at \\(14\\,\\text{m/s}\\). How high does it rise?"
SEEING = replace(default_capabilities("local"), vision=True)
CAPTURE = "input/captured-question#/properties/"


def run(coro: Any) -> Any:
    return LOOP.run_until_complete(coro)


def images_in(provider: ScriptedProvider) -> list[bytes]:
    """Every image the provider was sent, decoded from its data URL."""
    out = []
    for request in provider.requests:
        for message in request["messages"]:
            content = message["content"]
            for part in content if isinstance(content, list) else []:
                if part.get("type") == "image_url":
                    url = part["image_url"]["url"]
                    assert url.startswith("data:image/jpeg;base64,")
                    out.append(base64.b64decode(url.split(",", 1)[1]))
    return out


def masked(photo: SafePhoto) -> SafePhoto:
    """A stand-in for the INP-20 local privacy pass: the image it would send, visibly different from the original."""
    image = Image.open(io.BytesIO(photo.jpeg)).convert("RGB")
    image.paste((0, 0, 0), (0, 0, image.width, image.height // 4))  # the top band, where a name would be
    out = io.BytesIO()
    image.save(out, "JPEG", quality=80)
    return SafePhoto(out.getvalue(), image.width, image.height)


def reader_engine(tmp_path: Path, *, cloud_on: bool = True, local_sees: bool = True) -> tuple[Any, Any, Any]:
    """An engine whose main local model reads photos (or not), with a cloud vision reader configured for the slot."""
    cloud = ScriptedProvider({"vision": [reply(READ)] * 5}, kind="cloud",
                             caps={"vision-model": replace(default_capabilities("cloud"), vision=True)})  # fmt: skip

    def configure(data: dict[str, Any]) -> None:
        data["cloud"]["enabled"] = True
        data["auxiliary"]["vision"]["model"] = "cloud:primary/vision-model"

    engine, local = run(make_engine(tmp_path, {"vision": [reply(READ)] * 5}, overrides=configure, cloud=cloud,
                                    worker=False))  # fmt: skip
    if local_sees:
        local.caps["qwen3-vl-8b"] = SEEING
    engine.deps.router.cloud_on = lambda role: cloud_on and role == "vision"  # type: ignore[method-assign]
    return engine, local, cloud


def read(engine: Any, **kw: Any) -> PhotoReading:
    reading: PhotoReading = run(engine.read_photo(_photo_with_gps(), **kw))
    return reading


def no_metadata(jpeg: bytes) -> bool:
    opened = Image.open(io.BytesIO(jpeg))
    return opened.format == "JPEG" and not opened.getexif().get_ifd(GPS_IFD) and b"Exif\x00\x00" not in jpeg


def mdl23_photos_local_unless_allowed(tmp_path: Path) -> None:
    engine, local, cloud = reader_engine(tmp_path)
    try:
        # The cloud tier is on: before anything is read, this photo's notice is asked for. Nothing has been sent.
        asked = read(engine, screen=masked)
        assert asked.status == "notice_needed" and asked.photo is not None and asked.text is None
        assert local.requests == [] and cloud.requests == []
        # Declined ("Read it on this computer"): read by the main local model, and no image reaches a cloud candidate.
        declined = read(engine, send_to_cloud=False, screen=masked)
        assert declined.status == "read" and declined.text == READ
        assert declined.reader is not None and declined.reader["path"] == "vision_model"
        assert declined.egress == {"left_device": False, "destination": "none"}
        assert cloud.requests == [] and images_in(cloud) == []
        (sent,) = images_in(local)
        assert sent == declined.photo.jpeg and no_metadata(sent), "the made-safe photo, never the original"
        (message,) = local.requests[-1]["messages"]
        assert local.requests[-1]["model"] == "qwen3-vl-8b" and message["content"][0]["text"] == READ_INSTRUCTION
        assert [m["role"] for m in local.requests[-1]["messages"]] == ["user"], "no history, no learner data (INP-22)"
        # Accepted, but with no local privacy pass on this device: still read locally (INP-20), never uploaded.
        unscreened = read(engine, send_to_cloud=True)
        assert unscreened.status == "read" and unscreened.egress == {"left_device": False, "destination": "none"}
        assert cloud.requests == []
        # Accepted with the privacy pass: the cloud reader gets exactly the screened image, and nothing else.
        accepted = read(engine, send_to_cloud=True, screen=masked)
        assert accepted.status == "read" and accepted.egress == {"left_device": True, "destination": "cloud_tier"}
        assert accepted.reader is not None and accepted.reader["path"] == "cloud_vision"
        (uploaded,) = images_in(cloud)
        assert accepted.photo is not None and uploaded == masked(accepted.photo).jpeg
        assert uploaded != accepted.photo.jpeg, "the screened image, not the one kept on the device"
        assert no_metadata(uploaded) and len(images_in(local)) == 2, "the local reader was not called for it"
        for reading in (declined, accepted):
            assert contract_errors(CAPTURE + "reader", reading.reader) == []
            assert contract_errors(CAPTURE + "egress", reading.egress) == []
    finally:
        run(close(engine))


def test_cloud_tier_off_reads_locally_without_asking(tmp_path: Path) -> None:
    engine, local, cloud = reader_engine(tmp_path, cloud_on=False)
    try:
        reading = read(engine, screen=masked)
        assert reading.status == "read" and reading.egress == {"left_device": False, "destination": "none"}
        assert cloud.requests == [] and len(images_in(local)) == 1
    finally:
        run(close(engine))


def test_a_cloud_failure_falls_back_to_the_local_reader(tmp_path: Path) -> None:
    engine, local, cloud = reader_engine(tmp_path)
    cloud.script = {"vision": [{"error": {"status": 503}}] * 10}
    try:
        reading = read(engine, send_to_cloud=True, screen=masked)
        assert reading.status == "read" and reading.reader is not None and reading.reader["path"] == "vision_model"
        assert reading.egress == {"left_device": False, "destination": "none"}
        assert len(images_in(local)) == 1
    finally:
        run(close(engine))


def test_unsafe_or_unreadable_photos_never_reach_a_model(tmp_path: Path) -> None:
    engine, local, cloud = reader_engine(tmp_path)
    try:
        garbage = run(engine.read_photo(b"\x89PNG\r\n\x1a\n not really a picture", send_to_cloud=True))
        assert garbage.status == "rejected" and garbage.code == "unsupported_format" and garbage.photo is None
        huge = Image.new("RGB", (9000, 10))
        out = io.BytesIO()
        huge.save(out, "PNG")
        too_large = run(engine.read_photo(out.getvalue(), send_to_cloud=False))
        assert too_large.status == "rejected" and too_large.code == "image_too_large"
        assert local.requests == [] and cloud.requests == []
    finally:
        run(close(engine))


def test_no_vision_anywhere_turns_photo_reading_off(tmp_path: Path) -> None:
    """A text-only main model and the cloud tier off: off, with the capability notice (MDL-06, PRM-17)."""
    engine, local, cloud = reader_engine(tmp_path, cloud_on=False, local_sees=False)
    try:
        reading = read(engine, send_to_cloud=True, screen=masked)
        assert reading.status == "off" and reading.notice == "Photo reading isn't available on this computer yet."
        assert local.requests == [] and cloud.requests == []
    finally:
        run(close(engine))


def test_structured_reader_converts_native_boxes_and_uses_a_working_only_instruction(tmp_path: Path) -> None:
    import json

    from agent_core.engine.vision import WORKING_READ_INSTRUCTION

    region = {
        "region_id": "rgn_0",
        "kind": "working_line",
        "order": 0,
        "text": "$x=10$",
        "confidence": 0.9,
        "needs_confirmation": False,
        "low_confidence_spans": [],
        "language": "en",
        "direction": "ltr",
        "bbox": {"x": 100, "y": 250, "w": 300, "h": 80},
        "number_label": None,
        "diagram_description": None,
        "table": None,
    }
    engine, local = run(
        make_engine(tmp_path, {"vision": [reply(json.dumps({"regions": [region], "refusal": None}))]}, worker=False)
    )
    local.caps["qwen3-vl-8b"] = SEEING
    try:
        reading = read(engine, send_to_cloud=False, structured=True, purpose="working")
        assert reading.status == "read" and reading.regions
        assert reading.regions[0]["bbox"] == {"x": 0.1, "y": 0.25, "w": 0.3, "h": 0.08}
        assert reading.regions[0]["text"] == r"\(x=10\)"
        request = local.requests[0]
        assert any(
            WORKING_READ_INSTRUCTION in part["text"]
            for message in request["messages"]
            for part in message["content"]
            if isinstance(part, dict) and part.get("type") == "text"
        )
    finally:
        run(close(engine))
