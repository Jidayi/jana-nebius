"""The O level mock papers of the Chemistry, Accounting and Mathematics packs (ASM-15, ASM-22, CUR-31).

The papers are generated by scripts/content/mock_papers/gen.py from each pack's own items. These tests read the
committed source tree: every paper matches its blueprint within one item, each subject has the S2 count of papers,
and the items the papers name (the mock-reserved pool) still leave every KC the S2 practice minimums.
"""

from __future__ import annotations

from collections import Counter
from functools import cache
from pathlib import Path
from typing import Any

import pytest
from agent_core.config import Settings
from agent_core.store.catalogue import diagnostic
from pack_builder import api, mocks
from pack_builder import source as tree
from pack_builder.build import load_source
from test_m8_authoring import repo as authoring_repo  # noqa: F401 - the authoring repository fixture

REPO = Path(__file__).resolve().parents[3]
SUBJECTS = ("chm", "acc", "mth")


def test_mock_items_do_not_satisfy_practice_coverage() -> None:
    from agent_core.store.catalogue import coverage_gaps
    from pack_builder.coverage import report
    from test_m8_authoring import _s2_tables

    settings = Settings()
    tables = _s2_tables(settings)
    assert coverage_gaps("S2", tables, settings) == []
    item = next(i for i in tables["items"] if not diagnostic(i))
    tables["mock_papers"][0]["sections"] = [{"questions": [{"item_id": item["id"]}]}]
    gaps = coverage_gaps("S2", tables, settings)
    assert gaps == [f"{item['kc_ids'][0]}: 9 published items, needs 10"]
    result = report({"pack_id": "pack.chm.o", "subject": "chm", "level": "o"}, tables, settings)
    assert not result["available"]
    row = next(r for r in result["per_kc"] if r["kc_id"] == item["kc_ids"][0])
    assert row["items"]["published"] == settings.coverage_s2_items_per_kc - 1


def _pack(subject: str) -> Path:
    return REPO / "content" / "curriculum" / subject / "o"


@cache
def _tables(subject: str) -> tuple[dict[str, Any], dict[str, list[dict[str, Any]]]]:
    source = load_source(_pack(subject))
    return source.pack, source.tables


@pytest.mark.parametrize("subject", SUBJECTS)
def asm15_blueprint_match(subject: str) -> None:
    settings = Settings()
    pack, tables = _tables(subject)
    papers = tables["mock_papers"]
    assert len(papers) >= settings.coverage_s2_mock_papers
    assert mocks.paper_problems(papers, pack, tables["items"], tables["curriculum_nodes"], tables["kcs"],
                                settings.mock_blueprint_weight_tolerance) == []  # fmt: skip
    for paper in papers:
        assert paper["review"]["status"] in ("verified", "in_eval_bank", "published")
        assert paper["total_marks"] == sum(q["marks"] for s in paper["sections"] for q in s["questions"])


@pytest.mark.parametrize("subject", SUBJECTS)
def test_mock_pool_keeps_practice_minimums(subject: str) -> None:
    """The items on mock papers are reserved (ASM-22): each KC keeps the S2 item and diagnostic counts (CUR-31)
    in the items left for practice, counting those students have: a published item, and an edited one whose new
    version is in the pipeline while its published version stays live (CUR-19)."""
    settings = Settings()
    source = load_source(_pack(subject))
    tables = source.tables
    reserved = {q["item_id"] for p in tables["mock_papers"] for s in p["sections"] for q in s["questions"]}
    assert reserved

    def live(item: dict[str, Any]) -> bool:
        history = (source.authoring.get(str(item["id"])) or {}).get("history") or []
        return item["review"]["status"] == "published" or "published" in history

    free = [i for i in tables["items"] if i["id"] not in reserved and live(i)]
    counts = Counter(k for i in free for k in i["kc_ids"])
    diagnostics = Counter(k for i in free if diagnostic(i) for k in i["kc_ids"])
    for kc in [k for k in tables["kcs"] if k["status"] == "active"]:
        assert counts[kc["id"]] >= settings.coverage_s2_items_per_kc, kc["id"]
        assert diagnostics[kc["id"]] >= settings.coverage_s2_diagnostic_items_per_kc, kc["id"]


def test_bank_takes_verified_mock_papers(authoring_repo: Any) -> None:  # noqa: F811
    """A verified mock paper enters the evaluation bank with the other records, so the signing service, which wants
    every reviewed record banked (CUR-22), can publish the pack (ASM-15, CUR-19)."""
    repo = authoring_repo
    items = [repo.record(f"itm.phy.o.motion.000{n}") for n in range(1, 4)]
    questions = [{"question_id": str(n), "item_id": i["id"], "marks": mocks.item_marks(i), "kc_ids": i["kc_ids"]}
                 for n, i in enumerate(items, 1)]  # fmt: skip
    marks = sum(q["marks"] for q in questions)
    paper = {"id": "mck.phy.o.0001", "version": "0.1.0", "subject": "phy", "level": "o", "paper_kind": "section_mock",
             "title": "Motion: section mock", "duration_minutes": 30, "total_marks": marks, "calculator": True,
             "blueprint": {"topic_weights": {"cur.phy.o.motion_forces_and_energy": 1.0}},
             "sections": [{"section_id": "A", "title": "Calculations", "item_types": sorted({i["type"] for i in items}),
                           "marks": marks, "questions": questions}],
             "provenance": {"origin": "original", "licence": "LicenseRef-Own", "drafted_with_ai": False, "sources": []},
             "review": {"status": "verified", "reviewers": []},
             "authoring": {"drafted_by": "rev_author_test", "history": ["drafted", "verified"]}}  # fmt: skip
    tree.save_record(repo.pack, "mock_papers", paper)
    moved = api.bank(repo.ctx("lead"), repo.pack, held_out_share=0.0)
    assert "mck.phy.o.0001" in moved["in_eval_bank"]
    banked = repo.record("mck.phy.o.0001")
    assert banked["review"]["status"] == "in_eval_bank"
    assert banked["authoring"]["history"] == ["drafted", "verified", "in_eval_bank"]


def test_grade_scale_is_one_set_of_board_letters_per_pack() -> None:
    """A band shows only in the board's own letters, set once per pack (ASM-19, D27): a pack with none passes and
    shows no band; a pack's papers carry one consistent scale or none, with one more letter than boundaries, falling
    boundaries and distinct letters. The letters here are invented for the test, not a board's."""
    import copy

    boundaries = list(Settings().grade_boundaries)
    letters = ["P", "Q", "R", "S", "T"]
    papers = copy.deepcopy(_tables("chm")[1]["mock_papers"])
    assert mocks.grade_problems(papers) == []  # no letters anywhere: no band, and no build problem
    for paper in papers:
        paper["grade_config"] = {"boundaries": boundaries, "labels": letters}
    assert mocks.grade_problems(papers) == []
    first = papers[0]["id"]
    papers[0]["grade_config"] = {"boundaries": boundaries, "labels": letters[:-1]}
    problems = mocks.grade_problems(papers)
    assert any(p.startswith(f"{first}: 4 grade letters for 4 boundaries") for p in problems)
    assert any("different grade scales" in p for p in problems)
    papers[0]["grade_config"] = {"boundaries": sorted(boundaries), "labels": letters}
    assert any("fall strictly" in p for p in mocks.grade_problems(papers))
    papers[0]["grade_config"] = {"boundaries": boundaries, "labels": ["P", "P", "R", "S", " "]}
    assert any("distinct and not blank" in p for p in mocks.grade_problems(papers))
    del papers[0]["grade_config"]
    assert any("only some carry one" in p for p in mocks.grade_problems(papers))
