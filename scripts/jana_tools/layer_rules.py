"""ARC-18 dependency rules for Python, as data. `python -m jana_tools importlinter --write`
renders them into .importlinter; the lint stage runs import-linter on that file and
the layer tests check that the file is current and that every rule rejects a seeded import."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

AGENT_CORE = (
    "api", "engine", "prompts", "roles", "assets", "tools", "router", "providers",
    "memory", "learner", "retrieval", "store", "trace", "net", "config", "contracts",
)  # fmt: skip
# Generated wire types are shared by every module (TABLE ARC-18a, last paragraph).
SHARED = frozenset({"contracts"})

# Non-loopback network clients: only agent_core.net may import them (ARC-18, last line).
# import-linter cannot forbid stdlib submodules (http.client, urllib.request); the
# offline job catches their use at run time.
NETWORK_CLIENTS = (
    "httpx", "requests", "aiohttp", "urllib3", "websockets", "ftplib", "smtplib",
)  # fmt: skip
# Modules the sandboxed workers must never reach (ARC-18 worker rows; SEC-07 exclusions).
WORKER_FORBIDDEN = (
    "agent_core", "socket", "ssl", "http", "urllib", "subprocess", "ctypes", "multiprocessing", "pickle", "marshal",
    "httpx", "requests", "aiohttp", "urllib3", "websockets",
)  # fmt: skip


@dataclass(frozen=True)
class Row:
    name: str
    modules: tuple[str, ...]  # agent_core subpackages, or a worker root package
    may_import: frozenset[str]  # agent_core siblings it may import
    forbidden_external: tuple[str, ...] = ()

    def forbidden_siblings(self) -> list[str]:
        if not self.modules[0].startswith("agent_core."):
            return []
        own = {m.removeprefix("agent_core.") for m in self.modules}
        return [m for m in AGENT_CORE if m not in own | self.may_import | SHARED]


def _core(*names: str) -> tuple[str, ...]:
    return tuple(f"agent_core.{n}" for n in names)


ROWS: tuple[Row, ...] = (
    Row("api", _core("api"), frozenset({"engine", "store", "config"}), NETWORK_CLIENTS),
    Row(
        "engine",
        _core("engine"),
        frozenset(
            {
                "prompts",
                "roles",
                "assets",
                "tools",
                "router",
                "memory",
                "learner",
                "retrieval",
                "store",
                "trace",
                "config",
            }
        ),
        NETWORK_CLIENTS,
    ),
    Row("prompts", _core("prompts"), frozenset({"assets", "config"}), NETWORK_CLIENTS),
    Row("tools", _core("tools"), frozenset({"config"}), NETWORK_CLIENTS),
    Row("router-providers", _core("router", "providers"), frozenset({"config", "trace", "net"}), NETWORK_CLIENTS),
    Row("learner-memory", _core("learner", "memory"), frozenset({"store", "config"}), NETWORK_CLIENTS),
    Row("net", _core("net"), frozenset({"config", "store"})),
    Row("roles", _core("roles"), frozenset({"assets", "config"}), NETWORK_CLIENTS),
    Row("assets", _core("assets"), frozenset({"config"}), NETWORK_CLIENTS),
    Row("retrieval", _core("retrieval"), frozenset({"assets", "store", "config"}), NETWORK_CLIENTS),
    Row("store", _core("store"), frozenset({"config"}), NETWORK_CLIENTS),
    Row("trace", _core("trace"), frozenset({"store", "config"}), NETWORK_CLIENTS),
    Row("config", _core("config"), frozenset(), NETWORK_CLIENTS),
    Row("tool-worker", ("tool_worker",), frozenset(), WORKER_FORBIDDEN),
    Row("perception-worker", ("perception_worker",), frozenset(), WORKER_FORBIDDEN),
    Row("study-worker", ("study_worker",), frozenset(), WORKER_FORBIDDEN),
)
# The generated contracts have no row of their own here; they may not import a network client either.
OTHER_CORE = _core("contracts")


def render_importlinter() -> str:
    lines = [
        "# GENERATED by `python -m jana_tools importlinter --write` from scripts/jana_tools/layer_rules.py.",
        "# Do not edit by hand. ARC-18 dependency rules for the Python packages.",
        "[importlinter]",
        "root_packages =",
        "    agent_core",
        "    tool_worker",
        "    perception_worker",
        "    study_worker",
        "    pack_builder",
        "    signing_service",
        "    cloud_gateway",
        "    ingest",
        "include_external_packages = True",
        "",
    ]
    for row in ROWS:
        core = row.modules[0].startswith("agent_core.")
        # In the agent core, network clients are forbidden as direct imports only: reaching them through
        # agent_core.net (which the row may import) is the point of that package. Workers forbid them transitively.
        targets = [f"agent_core.{m}" for m in row.forbidden_siblings()] + ([] if core else list(row.forbidden_external))
        lines += [
            f"[importlinter:contract:arc18-{row.name}]",
            f"name = ARC-18 {row.name}",
            "type = forbidden",
            "source_modules =",
            *(f"    {m}" for m in row.modules),
            "forbidden_modules =",
            *(f"    {t}" for t in targets),
            # Agent-core rows list the layers a module may import directly; an allowed layer may use its own
            # dependencies (the engine imports the router, which imports providers). Workers stay transitive.
            *(["allow_indirect_imports = True"] if core else []),
            "",
        ]
        if core and row.forbidden_external:
            lines += [
                f"[importlinter:contract:arc18-{row.name}-network]",
                f"name = ARC-18 {row.name} imports no network client directly",
                "type = forbidden",
                "source_modules =",
                *(f"    {m}" for m in row.modules),
                "forbidden_modules =",
                *(f"    {t}" for t in row.forbidden_external),
                "allow_indirect_imports = True",
                "",
            ]
    lines += [
        "[importlinter:contract:arc18-network-clients]",
        "name = ARC-18 only agent_core.net imports a network client",
        "type = forbidden",
        "source_modules =",
        *(f"    {m}" for m in OTHER_CORE),
        "forbidden_modules =",
        *(f"    {t}" for t in NETWORK_CLIENTS),
        "",
    ]
    lines += [
        "[importlinter:contract:arc21-roles]",
        "name = ARC-21 specialist roles never reach learner state",
        "type = forbidden",
        "source_modules =",
        "    agent_core.roles",
        "forbidden_modules =",
        "    agent_core.learner",
        "    agent_core.memory",
        "    agent_core.store",
        "",
    ]
    lines += [
        "[importlinter:contract:aut33-no-keys-in-toolchain]",
        "name = AUT-33 the authoring toolchain never imports the signing service or its keys",
        "type = forbidden",
        "source_modules =",
        "    pack_builder",
        "forbidden_modules =",
        "    signing_service",
        "",
    ]
    lines += [
        "[importlinter:contract:arc12-gateway-only-server-side]",
        "name = ARC-12 SEC-20 shipped code never imports the cloud gateway or its key custody",
        "type = forbidden",
        "source_modules =",
        "    agent_core",
        "    tool_worker",
        "    perception_worker",
        "    pack_builder",
        "forbidden_modules =",
        "    cloud_gateway",
        "",
    ]
    lines += [
        "[importlinter:contract:ops24-ingest-server-side]",
        "name = OBS-17 OBS-20 OPS-24 the ingest is server-side: shipped code never imports it",
        "type = forbidden",
        "source_modules =",
        "    agent_core",
        "    tool_worker",
        "    perception_worker",
        "    pack_builder",
        "forbidden_modules =",
        "    ingest",
        "",
        "[importlinter:contract:lrn11-lrn13-reference-libraries-test-only]",
        "name = LRN-11 LRN-13 SEC-22 pyBKT, py-fsrs and scikit-learn are test-only: shipped code never imports them",
        "type = forbidden",
        "source_modules =",
        "    agent_core",
        "    tool_worker",
        "    perception_worker",
        "    pack_builder",
        "    signing_service",
        "    cloud_gateway",
        "    ingest",
        "forbidden_modules =",
        "    pyBKT",
        "    fsrs",
        "    sklearn",
        "",
        "[importlinter:contract:ops24-ingest-standalone]",
        "name = OPS-24 the ingest deploys on its own: it imports no device, worker or gateway package",
        "type = forbidden",
        "source_modules =",
        "    ingest",
        "forbidden_modules =",
        "    agent_core",
        "    tool_worker",
        "    perception_worker",
        "    cloud_gateway",
        "",
    ]
    return "\n".join(lines)


def importlinter_errors(root: Path) -> list[str]:
    path = root / ".importlinter"
    if not path.is_file() or path.read_text() != render_importlinter():
        return [".importlinter is stale; run: uv run python -m jana_tools importlinter --write"]
    return []
