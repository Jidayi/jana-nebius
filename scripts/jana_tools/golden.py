# --- step checking (golden and the seeded-error set) ------------------------------------------------------------


def _signed(n: int) -> str:
    return f"+ {n}" if n >= 0 else f"- {-n}"


def step_cases(rng: random.Random, count: int, prefix: str) -> list[dict[str, Any]]:
    """Linear-equation steps with labelled errors injected by construction, plus valid steps and the
    illegal-operation, dropped-term and solution-set cases."""
    cases: list[dict[str, Any]] = []
    kinds = ["valid", "sign", "arithmetic", "copy", "dropped_term", "illegal_operation", "lost", "extraneous"]
    for i in range(count):
        kind = kinds[i % len(kinds)]
        a, root = rng.choice([2, 3, 4, 5, 6]), rng.randint(2, 12)
        b = rng.choice([n for n in range(-15, 16) if n not in (0,)])
        c = a * root + b
        prev = f"{a}x {_signed(b)} = {c}"
        if kind == "valid":
            nxt, expect = f"{a}x = {c - b}", {"verdict": "valid"}
        elif kind == "sign":
            nxt, expect = f"{a}x = {c + b}", {"verdict": "invalid", "category": "sign"}
        elif kind == "arithmetic":
            nxt, expect = f"x = {root + rng.choice([1, 2, -1, 3])}", {"verdict": "invalid", "category": "arithmetic"}
            prev = f"{a}x = {a * root}"
        elif kind == "copy":
            given = rng.choice([13, 14, 15, 16, 17, 18, 19, 23, 24, 25, 26, 27, 28, 29, 31, 32, 34, 35])
            swapped = int(str(given)[::-1])
            prev, nxt = f"x + {given} = {given + root}", f"x + {swapped} = {given + root}"
            expect = {"verdict": "invalid", "category": "copy"}
            cases.append(_case(f"{prefix}_{i:04d}", {"prev": prev, "next": nxt, "givens": [given]}, expect))
            continue
        elif kind == "dropped_term":
            p, q = rng.randint(1, 9), rng.randint(1, 9)
            prev, nxt = f"(x + {p})(x + {q})", _plain(x**2 + p * q)
            expect = {"verdict": "invalid", "category": "dropped_term"}
        elif kind == "illegal_operation":
            p = rng.randint(2, 9)
            prev, nxt = rng.choice([(f"log(x + {p})", f"log(x) + log({p})"), (f"(x + {p})/{p}", "x")])
            expect = {"verdict": "invalid", "category": "illegal_operation"}
        elif kind == "lost":
            p = rng.randint(2, 9)
            prev, nxt = f"x^2 = {p}x", f"x = {p}"
            expect = {"verdict": "valid_but_lost_solutions"}
        else:
            prev, nxt = f"x = {root}", f"x^2 = {root * root}"
            expect = {"verdict": "valid_but_extraneous"}
        cases.append(_case(f"{prefix}_{i:04d}", {"prev": prev, "next": nxt}, expect))
    return cases


