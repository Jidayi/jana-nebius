IDENTITIES = [
    ("sin^2 x + cos^2 x", "1"),
    ("(x+1)^2", "x^2 + 2x + 1"),
    ("(x-1)(x+1)", "x^2 - 1"),
    ("2sin x cos x", "sin(2x)"),
    ("tan x", "sin x / cos x"),
    ("e^(2ln x)", "x^2"),
    ("ln(x^3)", "3ln x"),
    ("1/x + 1/(x+1)", "(2x+1)/(x(x+1))"),
    ("(x^3 - 1)/(x - 1)", "x^2 + x + 1"),
]


def equivalence_cases(rng: random.Random) -> list[dict[str, Any]]:
    cases = [
        _case("equiv_doc_pythagorean", {"a": "sin^2 x + cos^2 x", "b": "1"}, {"verdict": "equivalent"}, "hand"),
        _case("equiv_doc_domain", {"a": "(x^2-1)/(x-1)", "b": "x+1"}, {"verdict": "equivalent_on_domain"}, "hand"),
        _case("equiv_doc_sqrt_real", {"a": "sqrt(x^2)", "b": "x"}, {"verdict": "not_equivalent"}, "hand"),
        _case(
            "equiv_doc_sqrt_positive",
            {"a": "sqrt(x^2)", "b": "x", "assumptions": {"x": ["positive"]}},
            {"verdict": "equivalent"},
            "hand",
        ),
        _case("equiv_equations_scaled", {"a": "2x = 4", "b": "x = 2"}, {"verdict": "equivalent"}, "hand"),
        _case("equiv_equations_lost_root", {"a": "x^2 = 4", "b": "x = 2"}, {"verdict": "not_equivalent"}, "hand"),
        _case("equiv_inequality_flipped", {"a": "x > 3", "b": "3 < x"}, {"verdict": "equivalent"}, "hand"),
    ]
    for i, (a, b) in enumerate(IDENTITIES):
        domain = i in (5, 6, 7, 8)
        cases.append(
            _case(
                f"equiv_identity_{i:02d}",
                {"a": a, "b": b, **({"assumptions": {"x": ["positive"]}} if domain and i in (5, 6) else {})},
                {"verdict": "equivalent_on_domain" if i == 8 else "equivalent"},
                "hand",
            )
        )
    for i in range(50):
        r, s = rng.randint(-9, 9), rng.randint(-9, 9)
        factored = f"(x {'-' if r >= 0 else '+'} {abs(r)})(x {'-' if s >= 0 else '+'} {abs(s)})"
        expanded = _plain(sp.expand((x - r) * (x - s)))
        cases.append(_case(f"equiv_factored_{i:03d}", {"a": factored, "b": expanded}, {"verdict": "equivalent"}))
        wrong = _plain(sp.expand((x - r) * (x - s)) + rng.choice([1, -1, 2, -2]))
        cases.append(_case(f"equiv_perturbed_{i:03d}", {"a": factored, "b": wrong}, {"verdict": "not_equivalent"}))
    return cases


