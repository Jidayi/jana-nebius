    cases = []
    for i in range(35):
        r, s = rng.randint(-6, 6), rng.randint(-6, 6)
        product = (x - r) * (x - s)
        cases.append(
            _case(
                f"simplify_expand_{i:03d}",
                {"expression": _plain(product), "form": "expanded"},
                {"status": "ok", "result": {"text": sp.sstr(sp.expand(product))}},
            )
        )
    for i in range(35):
        r, s = sorted(rng.sample(range(-6, 7), 2))
        cases.append(
            _case(
                f"simplify_factor_{i:03d}",
                {"expression": _plain(sp.expand((x - r) * (x - s))), "form": "factorised"},
                {"status": "ok", "result": {"text": sp.sstr(sp.factor((x - r) * (x - s)))}},
            )
        )
    for i in range(32):
        a, b = rng.randint(1, 9), rng.randint(1, 9)
        expr = sp.Rational(1, a) * x + sp.Rational(1, b) * x
        cases.append(
            _case(
                f"simplify_collect_{i:03d}",
                {"expression": f"x/{a} + x/{b}", "form": "simplest"},
                {"status": "ok", "result": {"text": sp.sstr(sp.simplify(expr))}},
            )
        )
    return cases


