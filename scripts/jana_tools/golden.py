        _case("parse_sqrt_symbol", {"text": "√x"}, {"text": "sqrt(x)"}, "hand"),
        _case("parse_cube_root", {"text": r"\sqrt[3]{x}"}, {"text": "x**(1/3)"}, "hand"),
        _case("parse_trig_power", {"text": "sin^2 x"}, {"text": "sin(x)**2"}, "hand"),
        _case("parse_log_base", {"text": "log_2(8)"}, {"text": "3"}, "hand"),
        _case("parse_abs", {"text": "|x-1|"}, {"text": "Abs(x - 1)"}, "hand"),
