def build() -> dict[str, dict[str, Any]]:
    rng = random.Random(SEED)
    physics = random.Random(golden_physics.SEED)
    sets = {
        "math_parse": parse_cases(rng),
        "math_check_equivalence": equivalence_cases(rng),
        "math_solve": solve_cases(rng) + suvat_cases() + golden_physics.quantity_cases(physics),
        "math_simplify": simplify_cases(rng),
        "math_evaluate": evaluate_cases(rng),
        "math_check_step": step_cases(rng, 104, "step"),
        "units_convert": units_convert_cases(rng),
        "units_check_dimensions": units_dimension_cases(rng),
        "math_check_step.seeded_errors": step_cases(rng, 520, "seeded"),
        # physics (M12.b): its own seed, so the sets above are unchanged
        "phys_optics": golden_physics.optics_cases(physics),
        "phys_circuit": golden_physics.circuit_cases(physics),
        "phys_projectile": golden_physics.projectile_cases(physics),
    }
    stages = dict.fromkeys(sets, "S1") | golden_physics.STAGES  # M12.b physics sets are S2
    for name, cases in golden_maths.sets(random.Random(SEED + 12)).items():  # M12.a, its own seed
        sets[name], stages[name] = cases, "S2"
    for name, cases in golden_accounting.sets(random.Random(golden_accounting.SEED)).items():  # M12.d, its own seed
        sets[name], stages[name] = cases, "S2"
    for name, cases in golden_chemistry.sets(random.Random(golden_chemistry.SEED)).items():  # M12.c, its own seed
        sets[name], stages[name] = cases, "S2"
    return {
        name: {
            "tool": name.split(".")[0],
            "version": VERSIONS.get(name.split(".")[0], 1),
            "stage": stages[name],
            "provenance": PROVENANCE,
            "review": "pending",
            "authored_by": "implementation agent (draft)",
            "reviewed_by": None,
            "cases": cases,
        }
        for name, cases in sets.items()
    }


def write(root: Path = GOLDEN) -> list[Path]:
    root.mkdir(parents=True, exist_ok=True)
    written = []
    for name, data in build().items():
        path = root / f"{name}.yaml"
        path.write_text(yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=120))
        written.append(path)
    return written


def load(root: Path = GOLDEN) -> dict[str, dict[str, Any]]:
    return {p.name.removesuffix(".yaml"): yaml.safe_load(p.read_text()) for p in sorted(root.glob("*.yaml"))}


def matches(actual: Any, expected: Any) -> bool:
    """Subset match: every expected key is present with a matching value."""
    if isinstance(expected, dict):
        return isinstance(actual, dict) and all(k in actual and matches(actual[k], v) for k, v in expected.items())
    if isinstance(expected, list):
        return (
            isinstance(actual, list)
            and len(actual) == len(expected)
            and all(matches(a, e) for a, e in zip(actual, expected, strict=True))
        )
    return bool(actual == expected)


def result_sha256(value: Any) -> str:
    """The worker's result hash (CheckRecord.result_sha256), computed the same way as the server."""
    import hashlib
    import json

    canonical = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True, default=str)
    return hashlib.sha256(canonical.encode()).hexdigest()


def run(case: dict[str, Any], tool: str, settings: dict[str, Any] | None = None) -> Any:
    """Run one case in-process exactly as the worker would (same seed and parameters)."""
    from tool_worker.functions import FUNCTIONS
    from tool_worker.protocol import WorkerError
    from tool_worker.registry import CallContext

    seed = int(result_sha256(case["args"])[:16], 16)
    context = CallContext(
        "golden", "chk_01JZ0000000000000000000001", {}, {}, lambda: False, seed=seed, settings=settings or {}
    )
    try:
        value, _ = FUNCTIONS[tool].implementation(case["args"], context)
    except WorkerError as error:
        return {"error": int(error.code), "message": error.message}
    return value


