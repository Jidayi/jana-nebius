def fingerprints() -> dict[str, str]:
    """case id -> result_sha256 for every golden case (VER-01: identical on every machine)."""
    out = {}
    for data in load().values():
        for case in data["cases"]:
            out[case["id"]] = result_sha256(run(case, data["tool"]))
    return dict(sorted(out.items()))
