"""Item types and their markers, TABLE ASM-03a (assessment.md), as generated data.

For each item type: the stage it is marked from (the first stage named) and the marker the table gives, with
markdown removed. The markers themselves are code (agent_core.engine.marking); this data lets tests and the pack
builder check that every type of the content-pack contract has exactly one marker."""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from .event_registry import table_lines

TABLE = "TABLE ASM-03a"


def parse_item_types(markdown: str) -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    for row in table_lines(markdown, TABLE):
        cells = [cell.strip() for cell in row.strip("|").split("|")]
        name = re.match(r"^`([a-z_]+)`\s*\(([^)]*)\)", cells[0])
        if name is None:
            raise ValueError(f"{TABLE}: unreadable type cell {cells[0]!r}")
        stage = re.search(r"S[1-5]", name.group(2))
        if name.group(1) in out:
            raise ValueError(f"{TABLE}: {name.group(1)} is listed twice")
        out[name.group(1)] = {"stage": stage.group(0) if stage else "", "marker": cells[1].replace("`", "")}
    return out


def generate_item_types(spec_dir: Path, out: Path) -> None:
    markdown = (spec_dir / "assessment.md").read_text(encoding="utf-8")
    data = parse_item_types(markdown)
    digest = hashlib.sha256("\n".join(table_lines(markdown, TABLE)).encode()).hexdigest()
    out.mkdir(parents=True, exist_ok=True)
    (out / "item_types.py").write_text(
        "# GENERATED by `python -m jana_tools codegen` from TABLE ASM-03a of docs/specification/assessment.md\n"
        "# Do not edit: change the table and regenerate (ARC-30).\n"
        '"""Each item type with the stage it is marked from and its marker (ASM-03)."""\n\n'
        f'SOURCE_SHA256 = "{digest}"\n\n'
        f"ITEM_TYPES: dict[str, dict[str, str]] = {json.dumps(data, indent=4, ensure_ascii=False)}\n"
    )
