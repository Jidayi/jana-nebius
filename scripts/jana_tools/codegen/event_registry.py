"""The event-type registry of TABLE DAT-04a (data-model.md) as generated data: each type's sync class.

Only the type names and the class are taken: the first backticked words of the first column, and the first word of
the third. A type the table names twice, or a class other than `local` or `consented`, fails the generation."""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from .policies import read_policy

TABLE = "TABLE DAT-04a"
CLASSES = ("local", "consented")


def table_lines(markdown: str, table: str = TABLE) -> list[str]:
    """The table's rows: the pipe lines after its caption line, up to the first other line."""
    lines = markdown.splitlines()
    caption = next(i for i, line in enumerate(lines) if line.startswith(f"{table} — "))
    rows: list[str] = []
    for line in lines[caption + 1 :]:
        if line.startswith("|"):
            rows.append(line)
        elif rows:
            break
    return rows[2:]  # header and separator


def parse_registry(markdown: str) -> dict[str, str]:
    registry: dict[str, str] = {}
    for row in table_lines(markdown):
        cells = [cell.strip() for cell in row.strip("|").split("|")]
        sync_class = cells[2].split()[0]
        if sync_class not in CLASSES:
            raise ValueError(f"{TABLE}: unknown sync class {sync_class!r}")
        # Type names are the backticked words before any parenthesis (which lists payload fields, not types).
        for name in re.findall(r"`([a-z_]+)`", cells[0].split("(")[0]):
            if name in registry:
                raise ValueError(f"{TABLE}: {name} is listed twice")
            registry[name] = sync_class
    return registry


def generate_event_registry(spec_dir: Path, out: Path) -> None:
    raw, data = read_policy(spec_dir, "event_registry")
    digest = hashlib.sha256(raw).hexdigest()
    out.mkdir(parents=True, exist_ok=True)
    (out / "event_registry.py").write_text(
        "# GENERATED by `python -m jana_tools codegen` from TABLE DAT-04a of contracts/policies/event_registry.json\n"
        "# Do not edit: change the table and regenerate (ARC-30).\n"
        '"""Every event type and its sync class (DAT-04)."""\n\n'
        f'SOURCE_SHA256 = "{digest}"\n\n'
        f"SYNC_CLASS: dict[str, str] = {json.dumps(data, indent=4)}\n"
    )
