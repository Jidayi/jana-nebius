"""Design tokens for the UI, generated from the token contract (DSN-01): seeds stay in the contract; roles become CSS
custom properties for both themes, the Tailwind 4 theme maps its keys onto the roles, and a TypeScript module carries
the values and contrast requirements the governance tests check (DSN-03). Prose (`usage`, `note`, `$comment`) stays in
the specification.

- `tokens.css`: `:root` (light), `[data-theme="dark"]`, and the reduced-motion overrides (DSN-09); the print theme of
  reports as `--print-*` properties (DSN-22).
- `theme.css`: the Tailwind `@theme` block. Default palettes, radii, sizes, weights, shadows and stacking levels are
  reset, so a class outside the tokens does not exist. `z-<level>` comes from the `zIndex` group, and `text-body`
  follows the "Board and chat text size" setting (`--text-scale`, DSN-07), which the app sets on the root element.
- `tokens.ts`: the same values as data.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

PROSE = frozenset({"usage", "note", "$comment", "description"})
WEIGHTS = {"regular": 400, "medium": 500, "semibold": 600}


def _strip(node: Any) -> Any:
    if isinstance(node, dict):
        return {k: _strip(v) for k, v in node.items() if k not in PROSE}
    if isinstance(node, list):
        return [_strip(v) for v in node]
    return node


def _header(digest: str, comment: str) -> str:
    return (
        f"{comment} GENERATED by `python -m jana_tools codegen` from packages/ui/tokens.json\n"
        f"{comment} source sha256: {digest}\n"
        f"{comment} Do not edit: change the token contract and regenerate (DSN-01).\n"
    )


def _css_header(digest: str) -> str:
    return "".join(f"/* {line.removeprefix('# ')} */\n" for line in _header(digest, "#").strip().split("\n"))


def _css_block(selector: str, props: list[tuple[str, str]]) -> str:
    return selector + " {\n" + "".join(f"  --{name}: {value};\n" for name, value in props) + "}\n"


def generate_tokens(tokens_file: Path, out: Path) -> None:
    raw = tokens_file.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    tokens = _strip(json.loads(raw))
    colours: dict[str, dict[str, Any]] = tokens["color"]
    aliases: dict[str, str] = tokens["aliases"]

    shadows: dict[str, dict[str, str]] = tokens["shadow"]
    light = [(f"color-{n}", c["light"]) for n, c in colours.items()]
    light += [(f"shadow-{n}", v["light"]) for n, v in shadows.items()]
    dark = [(f"color-{n}", c["dark"]) for n, c in colours.items()]
    dark += [(f"shadow-{n}", v["dark"]) for n, v in shadows.items()]
    alias_props = [(f"color-{a}", f"var(--color-{target})") for a, target in aliases.items()]
    shared: list[tuple[str, str]] = []
    shared += [(f"space-{k.replace('.', '_')}", f"{v}px") for k, v in tokens["space"].items()]
    shared += [(f"radius-{k}", f"{v}px") for k, v in tokens["radius"].items()]
    shared += [(f"border-{k}", f"{v}px") for k, v in tokens["border"].items()]
    for name, size in tokens["typeScale"].items():
        shared += [(f"text-{name}", f"{size['size']}px"), (f"leading-{name}", f"{size['lineHeight']}px"),
                   (f"weight-{name}", str(WEIGHTS[size["weight"]]))]  # fmt: skip
        if "letterSpacing" in size:
            shared.append((f"tracking-{name}", size["letterSpacing"]))
    math = tokens["math"]
    shared += [("math-board", f"{math['boardSize']}px"), ("math-inline-scale", str(math["inlineScale"])),
               ("math-display-scale", str(math["displayScale"]))]  # fmt: skip
    for name, family in tokens["font"]["family"].items():
        stack = ", ".join(f'"{f}"' if " " in f else f for f in family["stack"])
        shared.append((f"font-{name}", stack))
    motion = tokens["motion"]
    durations = [(f"duration-{k}", f"{v}ms") for k, v in motion["duration"].items()]
    shared += durations
    shared += [(f"ease-{k}", v) for k, v in motion["easing"].items()]
    shared += [(f"z-{k}", str(v)) for k, v in tokens.get("zIndex", {}).items()]
    if "textScale" in tokens:
        shared.append(("text-scale", str(tokens["textScale"]["default"])))
    shared.append(("reading-measure", f"{tokens['layout']['readingMeasureCh']}ch"))
    # DSN-17: the app frame's sizes and the target floor, for either layout direction (breakpoints stay in media
    # queries, which cannot read custom properties).
    layout = tokens["layout"]
    for key in ("columnMax", "composerMax", "headerHeight"):
        if key in layout:
            shared.append((f"layout-{key}", f"{layout[key]}px"))
    for group in ("railWidth", "tutorSplit"):
        shared += [(f"layout-{group}-{k}", f"{v}px") for k, v in layout.get(group, {}).items()]
    shared += [(f"target-{k}", f"{v}px") for k, v in tokens.get("target", {}).items()]
    # DSN-18: colours that are themselves the content are one value in both themes, never interface meaning.
    shared += [(f"content-{k}", v["value"]) for k, v in tokens.get("contentColour", {}).get("swatches", {}).items()]
    # DSN-22: the print theme of A4 reports, independent of the screen theme: its colours, its point-based type scale
    # and the page margin. The report's print stylesheet maps the roles onto these inside the printed report only.
    printed = tokens.get("print", {})
    shared += [(f"print-color-{k}", v) for k, v in printed.get("color", {}).items()]
    for name, size in printed.get("typeScalePt", {}).items():
        shared.append((f"print-text-{name}", f"{size['size']}pt"))
        if "lineHeight" in size:
            shared.append((f"print-leading-{name}", f"{size['lineHeight']}pt"))
        if "weight" in size:
            shared.append((f"print-weight-{name}", str(WEIGHTS[size["weight"]])))
    if "marginMm" in printed.get("page", {}):
        shared.append(("print-page-margin", f"{printed['page']['marginMm']}mm"))

    keep = set(motion["reducedMotion"]["keep"])
    reduced = [(n, "0ms") for n, _ in durations if not any(k.lower() in n.replace("-", "").lower() for k in keep)]
    tokens_css = (
        _css_header(digest)
        + "\n"
        + _css_block(":root", light + alias_props + shared)
        + "\n"
        # Alias custom properties resolve where they are declared. Re-declare them at each scoped theme so a
        # gallery or embedded preview cannot inherit an already-resolved colour from its parent's theme.
        + _css_block('[data-theme="light"]', light + alias_props)
        + "\n"
        + _css_block('[data-theme="dark"]', dark + alias_props)
        + "\n"
        + "@media (prefers-reduced-motion: reduce) {\n"
        + "".join(f"  :root {{ --{n}: {v}; }}\n" for n, v in reduced)
        + "}\n\n"
        + _css_block('[data-reduced-motion="true"]', reduced)
    )

    theme: list[tuple[str, str]] = [
        ("color-*", "initial"), ("radius-*", "initial"), ("text-*", "initial"), ("font-weight-*", "initial"),
        ("shadow-*", "initial"), ("font-*", "initial"), ("ease-*", "initial"), ("z-index-*", "initial"),
        ("spacing", "4px"),
    ]  # fmt: skip
    theme += [(f"color-{n}", f"var(--color-{n})") for n in [*colours, *aliases]]
    theme += [(f"radius-{k}", f"var(--radius-{k})") for k in tokens["radius"]]
    scaled = {"body"} if "textScale" in tokens else set()  # DSN-07: body (board and chat) text follows the setting
    for name, size in tokens["typeScale"].items():
        if name in scaled:
            theme += [(f"text-{name}", f"calc(var(--text-{name}) * var(--text-scale))"),
                      (f"text-{name}--line-height", f"calc(var(--leading-{name}) * var(--text-scale))")]  # fmt: skip
        else:
            theme += [(f"text-{name}", f"var(--text-{name})"), (f"text-{name}--line-height", f"var(--leading-{name})")]
        theme.append((f"text-{name}--font-weight", f"var(--weight-{name})"))
        if "letterSpacing" in size:
            theme.append((f"text-{name}--letter-spacing", f"var(--tracking-{name})"))
    theme += [(f"font-weight-{k}", str(v)) for k, v in WEIGHTS.items()]
    theme += [(f"font-{k}", f"var(--font-{k})") for k in tokens["font"]["family"]]
    theme += [(f"ease-{k}", f"var(--ease-{k})") for k in motion["easing"]]
    theme += [(f"shadow-{k}", f"var(--shadow-{k})") for k in shadows]
    theme += [(f"z-index-{k}", f"var(--z-{k})") for k in tokens.get("zIndex", {})]
    theme_css = _css_header(digest) + "\n@theme inline {\n" + "".join(f"  --{n}: {v};\n" for n, v in theme) + "}\n"
    # DSN-06, DSN-07: a size set in another face than the UI one (display and title in Funnel Display) carries it.
    faces = [(name, size["family"]) for name, size in tokens["typeScale"].items() if size.get("family", "ui") != "ui"]
    if faces:
        theme_css += (
            "\n@layer utilities {\n"
            + "".join(f"  .text-{name} {{ font-family: var(--font-{family}); }}\n" for name, family in faces)
            + "}\n"
        )

    data = {k: v for k, v in tokens.items() if k != "seeds"}
    tokens_ts = (
        _header(digest, "//")
        + "\n"
        + f"export const TOKENS = {json.dumps(data, indent=2, ensure_ascii=False)} as const;\n"
    )
    out.mkdir(parents=True, exist_ok=True)
    (out / "tokens.css").write_text(tokens_css)
    (out / "theme.css").write_text(theme_css)
    (out / "tokens.ts").write_text(tokens_ts)
