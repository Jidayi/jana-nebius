"""TypeScript types and precompiled runtime validators (packages/contracts-ts/src/generated)."""

from __future__ import annotations

import json
import subprocess
import tempfile
from pathlib import Path

from .. import REPO_ROOT
from .sources import Contract, bundled, header

NODE_GENERATOR = REPO_ROOT / "scripts" / "codegen" / "contracts-ts.mjs"


def generate_typescript(contracts: list[Contract], out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as scratch:
        prepared, canonical = Path(scratch) / "prepared", Path(scratch) / "canonical"
        for contract in contracts:
            for base, schema in ((prepared, bundled(contract, contracts)), (canonical, contract.schema)):
                target = base / contract.rel
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(json.dumps(schema, indent=1))
        job = {
            "prepared": str(prepared),
            "canonical": str(canonical),
            "out": str(out),
            "contracts": [
                {
                    "rel": c.rel,
                    "id": c.id,
                    "module": c.module,
                    "header": header(c, "//"),
                    "has_root": c.has_root,
                    "definitions": c.definitions,
                }
                for c in contracts
            ],
        }
        job_file = Path(scratch) / "job.json"
        job_file.write_text(json.dumps(job))
        subprocess.run(["node", str(NODE_GENERATOR), str(job_file)], check=True, cwd=REPO_ROOT)
    _write_compat(contracts, out)


def _write_compat(contracts: list[Contract], out: Path) -> None:
    """The tolerant reader's data for the client (API-35), from the same source as the agent core's compat.json."""
    from .python import compat_data

    events = compat_data(contracts)["events"]
    body = (
        "// GENERATED by `python -m jana_tools codegen` from contracts/api/events.schema.json\n"
        "// Do not edit: change the contract and regenerate (ARC-30).\n"
        "/** The tolerant reader's view of this build's event contract (API-35). */\n"
        f"export const ENVELOPE_FIELDS: readonly string[] = {json.dumps(events['envelope'])};\n"
        f"export const EVENT_FIELDS: Readonly<Record<string, readonly string[]>> = {json.dumps(events['types'])};\n"
        "/** Where an event uses an open enum (`x-open-enum`), with the values this build knows; `*` is any item. */\n"
        "export const OPEN_ENUMS: Readonly<Record<string, readonly { path: readonly string[]; "
        f"values: readonly string[] }}[]>> = {json.dumps(events['open_enums'])};\n"
    )
    (out / "compat.ts").write_text(body)  # exported by the package's src/index.ts
