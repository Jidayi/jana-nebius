"""Tool data for the agent core's registry, generated from their single sources (TOL-01, TOL-05, TOL-24):

- `register.py` from the specification's tool register (registers/toolsets.json), prose removed;
- `worker_schemas.py` from the worker's argument schemas (services/tool-worker/tool_worker/schemas), byte-for-byte
  the same objects the worker hashes into `schema_sha256`, so the handshake can detect drift.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

from .. import REPO_ROOT

WORKER_SCHEMAS = REPO_ROOT / "services" / "tool-worker" / "tool_worker" / "schemas"
RENDERER_SCHEMAS = REPO_ROOT / "packages" / "renderers" / "src" / "schemas"
SIM_SCENARIOS = REPO_ROOT / "packages" / "renderers" / "src" / "sims" / "scenarios.json"
SIM_PRESETS = REPO_ROOT / "packages" / "renderers" / "src" / "sims" / "presets.json"
PROSE_KEYS = frozenset({"$comment", "description", "note"})


def _strip(node: Any) -> Any:
    if isinstance(node, dict):
        return {k: _strip(v) for k, v in node.items() if k not in PROSE_KEYS}
    if isinstance(node, list):
        return [_strip(v) for v in node]
    return node


def _module(source: str, digest: str, name: str, value: Any, doc: str) -> str:
    return (
        (
            f"# GENERATED by `python -m jana_tools codegen` from {source}\n"
            f"# source sha256: {digest}\n"
            "# Do not edit: change the source and regenerate (ARC-30).\n"
            f'"""{doc}"""\n\n'
            "from typing import Any\n\n"
            f"{name}: dict[str, Any] = {json.dumps(value, indent=1, sort_keys=False, ensure_ascii=False)}\n"
        )
        .replace(": true", ": True")
        .replace(": false", ": False")
        .replace(": null", ": None")
    )


def generate_tool_data(out: Path, registers_dir: Path, worker_schemas: Path = WORKER_SCHEMAS) -> None:
    out.mkdir(parents=True, exist_ok=True)
    register_file = registers_dir / "toolsets.json"
    raw = register_file.read_bytes()
    register = _strip(json.loads(raw))
    (out / "register.py").write_text(
        _module(
            "contracts/registers/toolsets.json",
            hashlib.sha256(raw).hexdigest(),
            "REGISTER",
            register,
            "The tool register: toolsets, tool metadata (TABLE TOL-03a), role grants and profiles.",
        )
    )
    schemas = {}
    digest = hashlib.sha256()
    for path in sorted(worker_schemas.glob("*.json")):
        digest.update(path.read_bytes())
        schemas[path.stem] = json.loads(path.read_text())
    (out / "worker_schemas.py").write_text(
        _module(
            "services/tool-worker/tool_worker/schemas/*.json",
            digest.hexdigest(),
            "WORKER_SCHEMAS",
            schemas,
            "The worker functions' argument schemas, identical to the worker's own (compared by schema_sha256).",
        )
    )
    (out / "__init__.py").write_text(
        "# GENERATED by `python -m jana_tools codegen`. Do not edit.\n"
        '"""Generated tool data: the register and the worker argument schemas."""\n'
    )
    subprocess.run([sys.executable, "-m", "ruff", "format", "--quiet", str(out)], check=True)


def generate_visual_data(
    out: Path,
    registers_dir: Path,
    renderer_schemas_dir: Path = RENDERER_SCHEMAS,
    scenarios: Path = SIM_SCENARIOS,
    presets: Path = SIM_PRESETS,
) -> None:
    """`visual_catalogue.py` from the visual catalogue register (VSL-02), prose removed, `kind_schemas.py` from the
    renderer-owned params schemas, `sim_scenarios.py` from the simulations' predict scenarios (VSL-47) and
    `sim_presets.py` from the presets a simulation's `preset_id` names (VSL-46)."""
    out.mkdir(parents=True, exist_ok=True)
    source = registers_dir / "visual-catalogue.json"
    raw = source.read_bytes()
    catalogue = _strip(json.loads(raw))
    (out / "visual_catalogue.py").write_text(
        _module(
            "contracts/registers/visual-catalogue.json",
            hashlib.sha256(raw).hexdigest(),
            "VISUAL_CATALOGUE",
            catalogue,
            "The visual catalogue register: every kind with renderer, subjects, levels, stage, number rule and tools.",
        )
    )
    # The params schemas of kinds the specification has no contract for: the registered renderer owns them (VSL-09),
    # and the engine's one validator applies the same objects (VSL-15 stage 4).
    renderer_schemas, digest = {}, hashlib.sha256()
    for path in sorted(renderer_schemas_dir.glob("*.schema.json")):
        digest.update(path.read_bytes())
        renderer_schemas[path.name.removesuffix(".schema.json")] = json.loads(path.read_text())
    (out / "kind_schemas.py").write_text(
        _module(
            "packages/renderers/src/schemas/*.schema.json",
            digest.hexdigest(),
            "KIND_SCHEMAS",
            renderer_schemas,
            "Renderer-owned params schemas, by kind, for the kinds with no contract in the specification.",
        )
    )
    # The predict, observe, explain scenarios (VSL-47): the engine fills a request's starting values from them.
    raw = scenarios.read_bytes()
    (out / "sim_scenarios.py").write_text(
        _module(
            "packages/renderers/src/sims/scenarios.json",
            hashlib.sha256(raw).hexdigest(),
            "SIM_SCENARIOS",
            {s["id"]: s for s in json.loads(raw)["scenarios"]},
            "The simulations' predict, observe, explain scenarios, by id.",
        )
    )
    # The simulation presets (VSL-46, D114): the engine resolves a request's `preset_id` against them.
    raw = presets.read_bytes()
    (out / "sim_presets.py").write_text(
        _module(
            "packages/renderers/src/sims/presets.json",
            hashlib.sha256(raw).hexdigest(),
            "SIM_PRESETS",
            {s["id"]: s for s in json.loads(raw)["presets"]},
            "The simulations' presets (a gas container, an electrolysis cell), by id.",
        )
    )
    (out / "__init__.py").write_text(
        "# GENERATED by `python -m jana_tools codegen`. Do not edit.\n"
        '"""Generated asset data: the visual catalogue register, the renderer-owned kind schemas and the simulation\n'
        'scenarios and presets."""\n'
    )
    subprocess.run([sys.executable, "-m", "ruff", "format", "--quiet", str(out)], check=True)


def generate_endpoints(contracts_dir: Path, py_out: Path, ts_out: Path) -> None:
    """The command schema's `x-endpoints` table (API-23: authoritative) as data for the core's routes and the client.

    The schema bindings drop `x-` extensions with the prose, so the table is generated on its own: method, path,
    request and response definitions, auth scopes, error codes, stage and owning requirement."""
    source = contracts_dir / "api" / "commands.schema.json"
    raw = source.read_bytes()
    endpoints = [
        {
            "method": e["method"], "path": e["path"], "request": _definition(e["request"]),
            "response": _definition(e["response"]), "auth": e["auth"], "errors": e["errors"], "stage": e["stage"],
            "owner": e["owner"],
        }
        for e in json.loads(raw)["x-endpoints"]  # data fields only: prose stays in the specification
    ]  # fmt: skip
    digest = hashlib.sha256(raw).hexdigest()
    origin = "contracts/api/commands.schema.json (x-endpoints)"
    py_out.parent.mkdir(parents=True, exist_ok=True)
    py_out.write_text(
        _module(
            origin,
            digest,
            "ENDPOINTS_BY_KEY",
            {f"{e['method']} {e['path']}": e for e in endpoints},
            "Endpoints of the local API, keyed by `METHOD path` (API-23).",
        )
    )
    ts_out.parent.mkdir(parents=True, exist_ok=True)
    ts_out.write_text(
        f"// GENERATED by `python -m jana_tools codegen` from {origin}\n"
        f"// source sha256: {digest}\n"
        "// Do not edit: change the source and regenerate (ARC-30).\n\n"
        "export interface Endpoint {\n"
        '  readonly method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n'
        "  readonly path: string;\n"
        "  readonly request: string | null;\n"
        "  readonly response: string | null;\n"
        "  readonly auth: readonly string[];\n"
        "  readonly errors: readonly string[];\n"
        "  readonly stage: string;\n"
        "  readonly owner: string;\n"
        "}\n\n"
        f"export const ENDPOINTS: readonly Endpoint[] = {json.dumps(endpoints, indent=2, ensure_ascii=False)};\n"
    )


def _definition(ref: str | None) -> str | None:
    """`#/$defs/Meta` -> `Meta` (a command body); another contract's definition keeps its contract:
    `https://jana.dev/contracts/lan/lan-compute#/$defs/LanServerStatus` -> `lan/lan-compute#/$defs/LanServerStatus`."""
    if ref is None:
        return None
    if ref.startswith("#/$defs/"):
        return ref.rsplit("/", 1)[-1]
    return ref.removeprefix("https://jana.dev/contracts/")


def generate_client_keys(out: Path) -> None:
    """The configuration keys the UI reads (declared once in agent_core.config.keys with `client=True`, ARC-28), as a
    TypeScript module of defaults and units."""
    from agent_core.config.keys import Settings, declaration

    rows = []
    for name, field in Settings.model_fields.items():
        extra = declaration(name)
        if extra.get("client"):
            rows.append((name, field.default, extra["unit"], extra["serves"]))
    digest = hashlib.sha256(json.dumps(rows).encode()).hexdigest()
    lines = [
        "// GENERATED by `python -m jana_tools codegen` from services/agent-core/agent_core/config/keys.py",
        f"// source sha256: {digest}",
        "// Do not edit: declare client keys in keys.py with client=True and regenerate (ARC-28).",
        "",
        "export const CLIENT_KEYS = {",
    ]
    for name, default, unit, serves in rows:
        lines.append(f"  /** {serves}; {unit} */")
        lines.append(f"  {name}: {json.dumps(default)},")
    lines += ["} as const;", "", "export type ClientKeys = { -readonly [K in keyof typeof CLIENT_KEYS]: number };", ""]
    out.mkdir(parents=True, exist_ok=True)
    (out / "keys.ts").write_text("\n".join(lines))


def generate_ui_tools(registers_dir: Path, out: Path) -> None:
    """The registered tool names, for the UI's activity-line templates (UXS-04: every tool maps to a family)."""
    raw = (registers_dir / "toolsets.json").read_bytes()
    register = json.loads(raw)
    names = sorted(t["name"] for toolset in register["toolsets"].values() for t in toolset["tools"])
    out.mkdir(parents=True, exist_ok=True)
    (out / "tools.ts").write_text(
        "// GENERATED by `python -m jana_tools codegen` from contracts/registers/toolsets.json\n"
        f"// source sha256: {hashlib.sha256(raw).hexdigest()}\n"
        "// Do not edit: change the register and regenerate (ARC-30).\n\n"
        f"export const TOOL_NAMES = {json.dumps(names, indent=2)} as const;\n\n"
        "export type ToolName = (typeof TOOL_NAMES)[number];\n"
    )


def generate_shell_keys(out: Path) -> None:
    """The configuration keys the Rust shell reads (declared once in agent_core.config.keys, `desktop_shell=True`)."""
    from agent_core.config.keys import Settings, declaration

    lines = []
    rows = []
    for name, field in Settings.model_fields.items():
        extra = declaration(name)
        if not extra.get("shell"):
            continue
        rows.append((name, field.default))
        const = name.upper()
        lines.append(f"/// {extra['serves']}; {extra['unit']}")
        default = field.default
        if isinstance(default, tuple):
            lines.append(f"pub const {const}: &[f64] = &[{', '.join(repr(float(v)) for v in default)}];")
        elif isinstance(default, int) and not isinstance(default, bool):
            lines.append(f"pub const {const}: usize = {default};")
        else:
            lines.append(f"pub const {const}: f64 = {float(default)!r};")
    digest = hashlib.sha256(json.dumps(rows, default=list).encode()).hexdigest()
    out.mkdir(parents=True, exist_ok=True)
    (out / "keys.rs").write_text(
        "// GENERATED by `python -m jana_tools codegen` from services/agent-core/agent_core/config/keys.py\n"
        f"// source sha256: {digest}\n"
        "// Do not edit: declare shell keys in keys.py with desktop_shell=True and regenerate (ARC-28).\n\n"
        + "\n".join(lines)
        + "\n"
    )
    (out / "mod.rs").write_text("// GENERATED by `python -m jana_tools codegen`. Do not edit.\npub mod keys;\n")


def generate_renderer_data(tokens_file: Path, out: Path) -> None:
    """The vetted renderers' own copy of the client keys and the content colour swatches (DSN-18): the renderer
    package imports nothing but React and the contracts (VSL-18), so its data is generated beside it."""
    generate_client_keys(out)
    raw = tokens_file.read_bytes()
    tokens = json.loads(raw)
    swatches = tokens.get("contentColour", {}).get("swatches", {})
    theme = {
        "color": {name: {"light": c["light"], "dark": c["dark"]} for name, c in tokens["color"].items()},
        "aliases": tokens["aliases"],
        "content": {name: s["value"] for name, s in swatches.items()},
    }
    (out / "theme.ts").write_text(
        "// GENERATED by `python -m jana_tools codegen` from packages/ui/tokens.json\n"
        f"// source sha256: {hashlib.sha256(raw).hexdigest()}\n"
        "// Do not edit. Token values by theme, for golden renders that resolve var(--color-…) (VSL-35, DSN-18).\n\n"
        f"export const THEME = {json.dumps(theme, indent=2)} as const;\n"
    )
    rows = {name: {"nameKey": s["nameKey"], "outline": "dashed" if s["value"] == "transparent" else "solid"}
            for name, s in swatches.items()}  # fmt: skip
    (out / "content_colours.ts").write_text(
        "// GENERATED by `python -m jana_tools codegen` from packages/ui/tokens.json\n"
        f"// source sha256: {hashlib.sha256(raw).hexdigest()}\n"
        "// Do not edit: change the tokens and regenerate (ARC-30).\n"
        "// Fill with var(--content-<name>) and name the colour by its nameKey.\n\n"
        f"export const CONTENT_COLOURS = {json.dumps(rows, indent=2)} as const;\n\n"
        "export type ContentColour = keyof typeof CONTENT_COLOURS;\n"
    )
