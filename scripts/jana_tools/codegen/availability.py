"""Subject-level availability by stage, TABLE CUR-01a (curriculum-and-content.md), as generated data.

Each registered subject code maps each level to the stages it is produced in, with the scope note a stage carries
(for example S1 physics is one topic). Rows without a registered code (new subjects, D32) are not data yet."""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from .event_registry import table_lines
from .policies import read_policy

TABLE = "TABLE CUR-01a"
STAGE = re.compile(r"^(S[1-5])(?:\s*\(([^)]*)\))?$")


def parse_availability(markdown: str) -> dict[str, dict[str, list[list[str | None]]]]:
    out: dict[str, dict[str, list[list[str | None]]]] = {}
    for row in table_lines(markdown, TABLE):
        cells = [cell.strip() for cell in row.strip("|").split("|")]
        code = re.match(r"^`([a-z]{3})`", cells[1])
        if code is None:
            continue
        levels: dict[str, list[list[str | None]]] = {}
        for level, cell in (("o", cells[2]), ("a", cells[3])):
            stages: list[list[str | None]] = []
            for part in (p.strip() for p in cell.split(",")):
                match = STAGE.match(part)
                if match is None:
                    raise ValueError(f"{TABLE}: unreadable stage {part!r} for {code.group(1)}")
                stages.append([match.group(1), match.group(2)])
            levels[level] = stages
        out[code.group(1)] = levels
    return out


def generate_availability(spec_dir: Path, out: Path) -> None:
    raw, data = read_policy(spec_dir, "availability")
    digest = hashlib.sha256(raw).hexdigest()
    out.mkdir(parents=True, exist_ok=True)
    (out / "availability.py").write_text(
        "# GENERATED by `python -m jana_tools codegen` from TABLE CUR-01a of\n"
        "# contracts/policies/availability.json\n"
        "# Do not edit: change the table and regenerate (ARC-30).\n"
        '"""The stages each subject-level pair is produced in, with any scope note (CUR-01)."""\n\n'
        f'SOURCE_SHA256 = "{digest}"\n\n'
        f"AVAILABILITY: dict[str, dict[str, list[list[str | None]]]] = {json.dumps(data, indent=4)}\n".replace(
            "null", "None"
        )
    )
