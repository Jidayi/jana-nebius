"""The storage contract (`contracts/data/schema.sql`, DAT-03) as generated data for the agent core's stores.

Comments are stripped (prose stays in the specification), string literals are kept intact, and the file is split on
its `-- @database <name>` markers: one SQL script per database kind, applied by the migration runner."""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path


def strip_comments(sql: str) -> str:
    out: list[str] = []
    i = 0
    while i < len(sql):
        ch = sql[i]
        if ch == "'":
            end = i + 1
            while end < len(sql):
                if sql[end] == "'" and sql[end + 1 : end + 2] == "'":
                    end += 2
                    continue
                if sql[end] == "'":
                    break
                end += 1
            out.append(sql[i : end + 1])
            i = end + 1
        elif sql.startswith("--", i):
            while i < len(sql) and sql[i] != "\n":
                i += 1
        else:
            out.append(ch)
            i += 1
    lines = [line.rstrip() for line in "".join(out).split("\n")]
    return "\n".join(line for line in lines if line.strip()) + "\n"


def split_databases(sql: str) -> dict[str, str]:
    parts = re.split(r"^-- @database (\w+)\s*$", sql, flags=re.MULTILINE)
    return {parts[i]: strip_comments(parts[i + 1]) for i in range(1, len(parts), 2)}


def generate_schema_sql(contracts_dir: Path, out: Path) -> None:
    raw = (contracts_dir / "data" / "schema.sql").read_bytes()
    databases = split_databases(raw.decode())
    digest = hashlib.sha256(raw).hexdigest()
    out.mkdir(parents=True, exist_ok=True)
    body = "\n".join(f"{name.upper()} = {json.dumps(sql)}\n" for name, sql in databases.items())
    (out / "schema.py").write_text(
        "# GENERATED by `python -m jana_tools codegen` from contracts/data/schema.sql\n"
        f"# source sha256: {digest}\n"
        "# Do not edit: change the storage contract and regenerate (ARC-30).\n"
        '"""The storage contract, one SQL script per database kind, comments removed (DAT-03)."""\n\n'
        f'SOURCE_SHA256 = "{digest}"\n\n'
        + body
        + "\nDATABASES = {"
        + ", ".join(f'"{name}": {name.upper()}' for name in databases)
        + "}\n"
    )
    (out / "__init__.py").write_text(
        '# GENERATED by `python -m jana_tools codegen`. Do not edit.\n"""Generated storage data."""\n'
    )
