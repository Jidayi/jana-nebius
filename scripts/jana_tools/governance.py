"""Security governance as code: the threat model (SEC-01) and boundary owners (SEC-02)."""

from __future__ import annotations

import re
import tomllib
from datetime import date
from pathlib import Path

from . import REPO_ROOT
from .spec import DOCS, ID, active, table_rows

BOUNDARIES = REPO_ROOT / "scripts" / "governance" / "boundaries.toml"
CODEOWNERS = REPO_ROOT / ".github" / "CODEOWNERS"
SECURITY_LEAD = "Security lead"
STAGE_EXIT_MILESTONES = ("m9", "m25", "m33", "m37", "m41")
_DATE = re.compile(r"(\d{4}-\d{2}-\d{2})")


# --- SEC-01 -----------------------------------------------------------------------------------


def _threat_rows(text: str) -> dict[str, list[str]]:
    rows = {}
    section = text.split("## Threats", 1)[-1].split("\n## ", 1)[0]
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and cells[0].isdigit():
            rows[cells[0]] = cells
    return rows


def latest_stage_gate(docs: Path) -> date | None:
    """Date of the latest accepted stage-exit milestone record, if any."""
    dates = []
    for milestone in STAGE_EXIT_MILESTONES:
        record = docs / "implementation" / f"{milestone}-acceptance.md"
        if not record.is_file():
            continue
        text = record.read_text()
        result = re.search(r"Result: (accepted[^·\n]*)", text)
        when = re.search(r"Date: (\d{4}-\d{2}-\d{2})", text)
        if result and when:
            dates.append(date.fromisoformat(when[1]))
    return max(dates, default=None)


def threat_model_errors(docs: Path = DOCS) -> list[str]:
    model_path = docs / "implementation" / "threat-model.md"
    if not model_path.is_file():
        return ["docs/implementation/threat-model.md is missing"]
    model = model_path.read_text()
    errors = []
    rows = _threat_rows(model)
    spec_rows = table_rows((docs / "specification" / "security.md").read_text(), "TABLE SEC-01a")
    for spec_row in spec_rows:
        num, mitigations = spec_row[0], set(ID.findall(spec_row[4]))
        if num not in rows:
            errors.append(f"threat {num} of TABLE SEC-01a is missing from the threat model")
        elif not mitigations <= set(ID.findall(rows[num][4])):
            errors.append(f"threat {num} drops mitigations {sorted(mitigations - set(ID.findall(rows[num][4])))}")
    for num, cells in rows.items():
        if not any(active(rid, docs) for rid in ID.findall(cells[4])):
            errors.append(f"threat {num} has no existing mitigating requirement")
    reviewed = re.search(r"Last reviewed: (\d{4}-\d{2}-\d{2})", model)
    gate = latest_stage_gate(docs)
    if not reviewed:
        errors.append("the threat model has no 'Last reviewed: <date>' line")
    elif gate and date.fromisoformat(reviewed[1]) < gate:
        errors.append(f"the threat model was last reviewed {reviewed[1]}, before the latest stage gate {gate}")
    boundaries = {r[0] for r in table_rows((docs / "specification" / "architecture.md").read_text(), "TABLE ARC-03a")}
    owned = set(re.findall(r"^\| (TB\d+) \| [A-Z][a-z]+ lead \|", model, re.MULTILINE))
    errors += [f"boundary {b} has no owning role in the threat model" for b in sorted(boundaries - owned)]
    return errors


# --- SEC-02 -----------------------------------------------------------------------------------


def load_boundaries(path: Path = BOUNDARIES) -> dict:
    data: dict = tomllib.loads(path.read_text())
    return data


def render_codeowners(data: dict) -> str:
    roles = data["roles"]
    lines = [
        "# GENERATED by `python -m jana_tools codeowners --write` from scripts/governance/boundaries.toml.",
        "# Do not edit by hand. Each tagged path needs its owning role and the Security lead (SEC-02).",
    ]
    for boundary in data["boundary"]:
        owners = sorted({roles[boundary["owner"]], roles[SECURITY_LEAD]})
        lines.append(f"\n# {boundary['id']}: {boundary['owner']}")
        lines += [f"{path} {' '.join(owners)}" for path in boundary["paths"]]
    return "\n".join(lines) + "\n"


def codeowners_errors(root: Path = REPO_ROOT, docs: Path = DOCS) -> list[str]:
    data = load_boundaries(root / "scripts" / "governance" / "boundaries.toml")
    errors = []
    roles = data.get("roles", {})
    errors += [f"role {r} has no GitHub handle" for r, h in roles.items() if not re.fullmatch(r"@[\w-]+(/[\w-]+)?", h)]
    if SECURITY_LEAD not in roles:
        errors.append("the Security lead role has no handle")
    ids = {b["id"] for b in data.get("boundary", [])}
    spec_ids = {r[0] for r in table_rows((docs / "specification" / "architecture.md").read_text(), "TABLE ARC-03a")}
    errors += [f"boundary {b} tags no files" for b in sorted(spec_ids - ids)]
    for boundary in data.get("boundary", []):
        if boundary.get("owner") not in roles:
            errors.append(f"boundary {boundary['id']} has an unknown owner role {boundary.get('owner')!r}")
        if not boundary.get("paths"):
            errors.append(f"boundary {boundary['id']} tags no files")
    if not errors:
        current = root / ".github" / "CODEOWNERS"
        if not current.is_file() or current.read_text() != render_codeowners(data):
            errors.append(".github/CODEOWNERS is stale; run: uv run python -m jana_tools codeowners --write")
    return errors


def owners_for(path: str, codeowners: str) -> list[str]:
    """Owners of a repository path under CODEOWNERS rules (last matching pattern wins).
    Supports the anchored file and directory patterns the generator emits."""
    owners: list[str] = []
    target = "/" + path.lstrip("/")
    for line in codeowners.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        pattern, *handles = line.split()
        if (pattern.endswith("/") and target.startswith(pattern)) or target == pattern:
            owners = handles
    return owners


def missing_approvals(changed: list[str], approvers: set[str], codeowners: str) -> list[str]:
    """Paths whose boundary owners have not all approved: each tagged path needs its owning role
    and the Security lead (when they are the same handle, one approval covers both)."""
    missing = []
    for path in changed:
        owners = owners_for(path, codeowners)
        lacking = [o for o in owners if o.lower() not in {a.lower() for a in approvers}]
        if lacking:
            missing.append(f"{path}: needs approval from {', '.join(lacking)}")
    return missing
