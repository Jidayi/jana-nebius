// TypeScript side of `python -m jana_tools codegen` (ARC-30, API-34). Reads a job file written by
// scripts/jana_tools/codegen/typescript.py and writes, under job.out:
//   <area>/<name>.ts   types (json-schema-to-typescript), one module per contract
//   validators.js      precompiled validators (Ajv standalone, JSON Schema 2020-12; no eval at run time)
//   validators.d.ts    their types
//   index.ts           namespaced type exports and validate()/errors() by contract name
import fs from "node:fs";
import path from "node:path";
import { compile } from "json-schema-to-typescript";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const job = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const NAMESPACE = "https://jana.dev/contracts/";
const TEMPLATE_HEADER =
  "// GENERATED by `python -m jana_tools codegen` from scripts/codegen/contracts-ts.mjs\n" +
  "// Do not edit: change the generator and regenerate (ARC-30).\n";
const write = (rel, text) => {
  const target = path.join(job.out, rel);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, text);
};
const identifier = (module) => module.replace(/[^A-Za-z0-9]+/g, "_");

// 1. Types, one module per contract. External references are resolved from the prepared copies.
for (const c of job.contracts) {
  const file = path.join(job.prepared, c.rel);
  const schema = JSON.parse(fs.readFileSync(file, "utf8"));
  const name = path.basename(c.rel, ".schema.json");
  const ts = await compile(schema, name, {
    cwd: path.dirname(file),
    bannerComment: c.header.trimEnd(),
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    ignoreMinAndMaxItems: true,
    style: { printWidth: 120 },
  });
  write(`${c.module}.ts`, ts);
}

// 2. Validators for every contract root, and for each definition of a definition catalogue.
const ajv = new Ajv2020({ strict: false, allErrors: true, inlineRefs: false, code: { source: true, esm: true, lines: false } });
addFormats(ajv, { mode: "full", formats: ["date", "date-time", "uri"] });
for (const c of job.contracts) ajv.addSchema(JSON.parse(fs.readFileSync(path.join(job.canonical, c.rel), "utf8")));
const keys = [];
for (const c of job.contracts) {
  const short = c.id.slice(NAMESPACE.length);
  if (c.has_root) keys.push([short, c.id]);
  if (!c.has_root || c.definitions.length) for (const d of c.definitions) keys.push([`${short}#/$defs/${d}`, `${c.id}#/$defs/${d}`]);
}
const refs = {};
keys.forEach(([, ref], i) => {
  ajv.getSchema(ref);
  refs[`v${i}`] = ref;
});
let code = standaloneCode(ajv, refs);
// Ajv's ESM output still requires its runtime helpers; turn them into imports.
const imports = new Map();
code = code.replace(/require\("([^"]+)"\)/g, (_, mod) => {
  if (!imports.has(mod)) imports.set(mod, `__runtime${imports.size}`);
  return imports.get(mod);
});
// Ajv's helpers are CommonJS: Node exposes module.exports as the default export, bundlers may expose the
// export itself. Normalise to module.exports so `helper.default` and `helper.fullFormats` work in both.
const importLines = [...imports]
  .map(([mod, id]) => `import * as ${id}_ns from "${mod}.js";\n` +
    `const ${id} = ${id}_ns.default && typeof ${id}_ns.default === "object" ? ${id}_ns.default : ${id}_ns;`)
  .join("\n");
write("validators.js", `${TEMPLATE_HEADER}/* eslint-disable */\n${importLines}\n${code.replace(/^"use strict";/, "")}\n`);
const names = keys.map(([short], i) => `  ${JSON.stringify(short)}: v${i},`).join("\n");
write(
  "validators.d.ts",
  `${TEMPLATE_HEADER}export interface ValidationError { instancePath: string; message?: string; keyword: string }\n` +
    `export type ValidateFunction = ((data: unknown) => boolean) & { errors?: ValidationError[] | null };\n` +
    keys.map((_, i) => `export declare const v${i}: ValidateFunction;`).join("\n") + "\n",
);

// 3. Index: namespaced types and validation by contract name.
const typeExports = job.contracts.map((c) => `export type * as ${identifier(c.module)} from "./${c.module}.js";`);
write(
  "index.ts",
  `${TEMPLATE_HEADER}import type { ValidateFunction, ValidationError } from "./validators.js";\n` +
    `import { ${keys.map((_, i) => `v${i}`).join(", ")} } from "./validators.js";\n\n` +
    typeExports.join("\n") + "\n\n" +
    `export type { ValidateFunction, ValidationError };\n\n` +
    `/** Validators by contract name: "api/events", or "api/commands#/$defs/StartTurn" for a catalogue definition. */\n` +
    `export const validators: Readonly<Record<string, ValidateFunction>> = {\n${names}\n};\n\n` +
    `export const NAMESPACE = ${JSON.stringify(NAMESPACE)};\n\n` +
    `function lookup(name: string): ValidateFunction {\n` +
    `  const key = name.startsWith(NAMESPACE) ? name.slice(NAMESPACE.length) : name;\n` +
    `  const validate = validators[key];\n` +
    `  if (!validate) throw new Error(\`unknown contract \${name}\`);\n` +
    `  return validate;\n}\n\n` +
    `/** Every violation as "<instance path>: <message>", in a stable order. */\n` +
    `export function errors(name: string, data: unknown): string[] {\n` +
    `  const validate = lookup(name);\n` +
    `  if (validate(data)) return [];\n` +
    `  return (validate.errors ?? []).map((e) => \`\${e.instancePath || "$"}: \${e.message ?? e.keyword}\`).sort();\n}\n\n` +
    `export function isValid(name: string, data: unknown): boolean {\n  return lookup(name)(data);\n}\n`,
);

// Learner clients only validate wire replies/events, saved learner records and registered visuals.
// Keep authoring, deployment and server contracts out of their initial module graph. The full index above
// remains available to Studio and the contract corpus. Both surfaces use the exact same Ajv functions.
const learnerKeys = keys.map(([short, ref], i) => ({ short, ref, i })).filter(({ short }) =>
  /^(api\/(commands|events)(#|$)|learning\/(student-records|journey)(#|$)|study\/workspace(#|$)|visuals\/)/.test(short));
const learnerRefs = Object.fromEntries(learnerKeys.map(({ ref, i }) => [`v${i}`, ref]));
let learnerCode = standaloneCode(ajv, learnerRefs);
const learnerImports = new Map();
learnerCode = learnerCode.replace(/require\("([^"]+)"\)/g, (_, mod) => {
  if (!learnerImports.has(mod)) learnerImports.set(mod, `__runtime${learnerImports.size}`);
  return learnerImports.get(mod);
});
const learnerImportLines = [...learnerImports].map(([mod, id]) =>
  `import * as ${id}_ns from "${mod}.js";\n` +
  `const ${id} = ${id}_ns.default && typeof ${id}_ns.default === "object" ? ${id}_ns.default : ${id}_ns;`).join("\n");
write("client-validators.js", `${TEMPLATE_HEADER}/* eslint-disable */\n${learnerImportLines}\n${learnerCode.replace(/^"use strict";/, "")}\n`);
write("client-validators.d.ts", `${TEMPLATE_HEADER}export type { ValidateFunction, ValidationError } from "./validators.js";\n` +
  `import type { ValidateFunction } from "./validators.js";\n` + learnerKeys.map(({ i }) => `export declare const v${i}: ValidateFunction;`).join("\n") + "\n");
const learnerIndex = fs.readFileSync(path.join(job.out, "index.ts"), "utf8")
  .replace(/import \{ v0,.*? \} from "\.\/validators.js";/, `import { ${learnerKeys.map(({ i }) => `v${i}`).join(", ")} } from "./client-validators.js";`)
  .replace(/export const validators: Readonly<Record<string, ValidateFunction>> = \{[\s\S]*?\n\};/,
    `export const validators: Readonly<Record<string, ValidateFunction>> = {\n${learnerKeys.map(({ short, i }) => `  ${JSON.stringify(short)}: v${i},`).join("\n")}\n};`);
write("client.ts", learnerIndex);
