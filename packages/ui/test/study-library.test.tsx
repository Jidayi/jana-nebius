import { cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, expect, test, vi } from "vitest";
import type { StudyContracts as W } from "@jana/client-core";
import { materialGroups, StudyLibrary } from "../src/learn/StudyLibrary.js";
import { MySets } from "../src/learn/StudyGenerate.js";
afterEach(cleanup);
const id = (n: number) => `src_${String(n).repeat(26)}`;
const now = "2026-10-24T12:00:00Z";
const source = (n: number, hash = "a".repeat(64), state = "ready") => ({ source_id: id(n), revision: 1, kind: "pdf", title: "notes.pdf", state, private: false, created_at: now, updated_at: now, readable_units: 69, unreadable_units: [], sha256: hash }) as W.SourceList["items"][number];
const set = (n: number, date: string, status = "ready") => ({ aid_id: `aid_${String(n).repeat(26)}`, kind: "quiz", sources: [{ source_id: id(n), revision: 1 }], title: "notes.pdf", private: false, status, created_at: date, progress: { questions_total: 10, questions_left: n } }) as W.StudySet;
test("identical uploads group by content while different files and private sources stay separate", () => {
  const privateSource = { source_id: id(4), revision: 1, kind: "pdf", private: true, created_at: now, updated_at: now } as const;
  const groups = materialGroups([source(1, undefined, "queued"), source(2), source(3, "b".repeat(64)), privateSource], []);
  expect(groups.map((g) => g.length).sort()).toEqual([1, 1, 2]);
  expect(groups.find((g) => g.length === 2)![0]!.source_id).toBe(id(2));
  expect(groups.flat().map((s) => s.source_id).sort()).toEqual([1, 2, 3, 4].map(id));
});
test("library expands all copies, searches, and archives a whole group reversibly", () => {
  const open = vi.fn(), archive = vi.fn(), sources = [source(1), source(2)];
  const { rerender } = render(<StudyLibrary sources={sources} sets={[]} archivedIds={[]} busy={false} onOpen={open} onArchive={archive} />);
  expect(screen.getAllByRole("button", { name: "notes.pdf Ready to study", exact: true })).toHaveLength(1);
  fireEvent.click(screen.getByRole("button", { name: /2 copies of notes.pdf/ }));
  const copies = screen.getByRole("list", { name: /2 copies of notes.pdf/ });
  const buttons = within(copies).getAllByRole("button");
  expect(buttons).toHaveLength(2);
  fireEvent.click(buttons[1]!);
  expect(open).toHaveBeenCalledWith(sources[1]);
  fireEvent.change(screen.getByRole("searchbox"), { target: { value: "missing" } });
  expect(screen.queryByRole("button", { name: "notes.pdf Ready to study", exact: true })).toBeNull();
  fireEvent.change(screen.getByRole("searchbox"), { target: { value: "" } });
  fireEvent.click(screen.getByRole("button", { name: "Actions for notes.pdf" }));
  fireEvent.click(screen.getByRole("menuitem", { name: "Archive material" }));
  expect(archive).toHaveBeenLastCalledWith([id(1), id(2)], true);
  rerender(<StudyLibrary sources={sources} sets={[]} archivedIds={[id(1), id(2)]} busy={false} onOpen={open} onArchive={archive} />);
  expect(screen.queryByRole("button", { name: "notes.pdf Ready to study", exact: true })).toBeNull();
  fireEvent.click(screen.getByRole("radio", { name: "Archived" }));
  expect(screen.getByRole("button", { name: "notes.pdf Ready to study", exact: true })).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Actions for notes.pdf" }));
  fireEvent.click(screen.getByRole("menuitem", { name: "Restore to library" }));
  expect(archive).toHaveBeenLastCalledWith([id(1), id(2)], false);
});
test("latest ready set leads a material family and every earlier version retains its own progress", () => {
  const open = vi.fn();
  const older = set(1, "2026-10-20T12:00:00Z"), ready = set(2, now), stale = set(3, "2026-10-25T12:00:00Z", "stale");
  render(<MySets sets={[older, stale, ready]} busy={false} contextual sourceAliases={new Map([1, 2, 3].map((n) => [id(n), id(1)]))} onOpen={open} />);
  const visible = screen.getAllByRole("button", { name: /^Quiz / });
  // happy-dom includes descendants of closed details in role queries.
  expect(visible).toHaveLength(3);
  expect(screen.getByText("2 questions left")).toBeTruthy();
  fireEvent.click(visible[0]!);
  expect(open).toHaveBeenLastCalledWith(ready);
  const disclosure = screen.getByText("Earlier Quiz sets (2)").closest("details")!;
  expect(disclosure.open).toBe(false);
  fireEvent.click(screen.getByText("Earlier Quiz sets (2)"));
  const rows = within(disclosure).getAllByRole("button");
  fireEvent.click(rows[0]!);
  expect(open).toHaveBeenLastCalledWith(older);
  expect(within(disclosure).getByText("1 question left")).toBeTruthy();
});
